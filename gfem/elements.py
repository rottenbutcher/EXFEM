# ---------------- 6-node wedge ----------------
_WP = [[1 / 6, 1 / 6], [2 / 3, 1 / 6], [1 / 6, 2 / 3]]


def _wedgeN(p):
    L = jnp.array([1 - p[0] - p[1], p[0], p[1]])
    return jnp.concatenate([L * (1 - p[2]) / 2, L * (1 + p[2]) / 2])


WEDGE_FACES = [[0, 1, 2], [3, 5, 4], [0, 3, 4, 1], [1, 4, 5, 2], [2, 5, 3, 0]]
WEDGE6 = ElementType("C3D6", 6, [[a, b, z] for z in (-_g2, _g2) for a, b in _WP], [1 / 6] * 6,
                     _wedgeN, 13, WEDGE_FACES, 6)

